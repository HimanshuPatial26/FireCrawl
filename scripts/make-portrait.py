"""Turn a headshot on a plain background into particle data for the About page.

Usage:
    python3 scripts/make-portrait.py path/to/headshot.png [--points 14000] [--preview preview.png]

Writes src/gl/portrait-data.js. Requires numpy and Pillow.
The background is found by flood-filling from the image border through pixels that are close to
the border colour or neutral and bright, so a plain grey or white backdrop works best.
"""
import argparse
import base64
from collections import deque
from pathlib import Path

import numpy as np
from PIL import Image

ap = argparse.ArgumentParser()
ap.add_argument("image")
ap.add_argument("--points", type=int, default=14000)
ap.add_argument("--max-side", type=int, default=240)
ap.add_argument("--threshold", type=float, default=34.0, help="colour distance treated as background")
ap.add_argument("--max-sat", type=float, default=30.0, help="neutral backdrops: max channel spread (0-255)")
ap.add_argument("--min-lum", type=float, default=0.45, help="neutral backdrops: minimum brightness (0-1)")
ap.add_argument("--preview")
ap.add_argument("--out", default=str(Path(__file__).resolve().parent.parent / "src" / "gl" / "portrait-data.js"))
args = ap.parse_args()

img = Image.open(args.image).convert("RGB")
scale = min(1.0, args.max_side / max(img.size))
if scale < 1.0:
    img = img.resize((round(img.width * scale), round(img.height * scale)), Image.LANCZOS)
rgb = np.asarray(img).astype(np.float32)
h, w, _ = rgb.shape

# background colour from the border, then flood fill from the border
border = np.concatenate([rgb[0], rgb[-1], rgb[:, 0], rgb[:, -1]])
bg = np.median(border, axis=0)
lum = (0.2126 * rgb[..., 0] + 0.7152 * rgb[..., 1] + 0.0722 * rgb[..., 2]) / 255.0
sat = rgb.max(axis=2) - rgb.min(axis=2)
# close to the border colour, or neutral and bright (handles a lit halo behind the head)
near_bg = (np.linalg.norm(rgb - bg, axis=2) < args.threshold) | ((sat < args.max_sat) & (lum > args.min_lum))
is_bg = np.zeros((h, w), bool)
q = deque()
for x in range(w):
    for y in (0, h - 1):
        if near_bg[y, x] and not is_bg[y, x]:
            is_bg[y, x] = True
            q.append((y, x))
for y in range(h):
    for x in (0, w - 1):
        if near_bg[y, x] and not is_bg[y, x]:
            is_bg[y, x] = True
            q.append((y, x))
while q:
    y, x = q.popleft()
    for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
        ny, nx = y + dy, x + dx
        if 0 <= ny < h and 0 <= nx < w and near_bg[ny, nx] and not is_bg[ny, nx]:
            is_bg[ny, nx] = True
            q.append((ny, nx))
subject = ~is_bg

# silhouette edge: subject pixels touching background
pad = np.pad(is_bg, 1, constant_values=True)
touch = pad[:-2, 1:-1] | pad[2:, 1:-1] | pad[1:-1, :-2] | pad[1:-1, 2:]
edge = subject & touch

ys, xs = np.nonzero(subject)
weights = 0.3 + lum[ys, xs] * 1.1 + edge[ys, xs] * 0.8
weights /= weights.sum()
rng = np.random.default_rng(7)
n = args.points
pick = rng.choice(len(xs), size=n, replace=n > len(xs), p=weights)
px, py = xs[pick], ys[pick]

# depth: a soft bulge around the head and shoulders, nudged forward by brightness
cols = np.nonzero(subject.any(axis=0))[0]
cx = (cols.min() + cols.max()) / 2.0
row_extent = np.array([max(1, subject[y].sum()) for y in range(h)], np.float32)
rx = np.maximum(row_extent[py] / 2.0, 1.0)
bulge = np.sqrt(np.clip(1.0 - ((px - cx) / rx) ** 2, 0.0, 1.0))
depth = np.clip(bulge * 0.8 + lum[py, px] * 0.2, 0.0, 1.0)

colour = rgb[py, px]
data = np.stack(
    [
        np.round(px / max(1, w - 1) * 255),
        np.round(py / max(1, h - 1) * 255),
        np.round(depth * 255),
        colour[:, 0],
        colour[:, 1],
        colour[:, 2],
    ],
    axis=1,
).astype(np.uint8)

b64 = base64.b64encode(data.tobytes()).decode("ascii")
Path(args.out).write_text(
    "// Generated by scripts/make-portrait.py. Do not edit by hand.\n"
    "// Six bytes per particle: x, y, depth, r, g, b (x and y are 0-255 across the image).\n"
    f"export const PORTRAIT = {{ aspect: {w / h:.4f}, count: {n}, data: '{b64}' }};\n"
)
print(f"image {w}x{h}, subject {subject.mean():.0%} of pixels, {n} particles -> {args.out} ({len(b64) / 1024:.0f} KB)")

if args.preview:
    s = 3
    canvas = np.zeros((h * s, w * s, 3), np.float32)
    bright = 0.35 + lum[py, px] * 1.25 + edge[py, px] * 0.5
    c = (colour / 255.0) * 0.75 + 0.25 * np.array([0.55, 0.75, 1.0])
    for x, y, cc, b in zip(px * s + rng.random(n) * s, py * s + rng.random(n) * s, c, bright):
        canvas[int(y), int(x)] += cc * b * 0.9
    Image.fromarray((np.clip(canvas, 0, 1) * 255).astype(np.uint8)).save(args.preview)
    print("preview", args.preview)
